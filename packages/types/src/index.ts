// ============================================================================
// 2. Standard API Error Contract (RFC 7807 Problem Details)
// ============================================================================

/**
 * Individual field validation failure item.
 */
export interface FieldError {
  field: string;
  message: string;
}

/**
 * RFC 7807 Problem Details representation for all API and gateway errors.
 */
export interface StandardErrorResponse {
  /**
   * A URI reference that identifies the problem type.
   * e.g., "https://api.diety.org/errors/validation-failed"
   */
  type: string;

  /**
   * A short, human-readable summary of the problem type.
   */
  title: string;

  /**
   * The HTTP status code generated by the origin server.
   */
  status: number;

  /**
   * A human-readable explanation specific to this occurrence of the problem.
   */
  detail: string;

  /**
   * A URI reference that identifies the specific occurrence of the problem.
   */
  instance: string;

  /**
   * Internal machine-readable application error code.
   * e.g., "ERR_VALIDATION_FAILED", "ERR_ESCROW_INSUFFICIENT_FUNDS"
   */
  code: string;

  /**
   * ISO 8601 UTC timestamp of when the error occurred.
   */
  timestamp: string;

  /**
   * Optional field-level validation breakdowns (typically for 422 Unprocessable Entity).
   */
  errors?: FieldError[] | undefined;
}

